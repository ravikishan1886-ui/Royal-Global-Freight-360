import { GoogleGenAI } from "@google/genai";
import { NextRequest, NextResponse } from "next/server";

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const { message, shipmentContext, activeRole, taskType } = body;

    if (!message) {
      return NextResponse.json({ error: "Message is required" }, { status: 400 });
    }

    if (process.env.GEMINI_API_KEY) {
      try {
        const ai = new GoogleGenAI({
          apiKey: process.env.GEMINI_API_KEY,
          httpOptions: {
            headers: {
              "User-Agent": "aistudio-build",
            },
          },
        });

        const systemInstruction = `You are the FREIGHTFLOW 360 AI Logistics Specialist & Documentation Copilot.
You specialize in international supply chains, container shipping, air freight, customs regulations (WCO, Indian CBIC, EU TARIC, US CBP), Incoterms 2020, and multi-modal logistics.
Role Context of Current User: ${activeRole || "Freight Forwarder"}
Task Context: ${taskType || "General Assistance"}
Shipment Data in Context: ${shipmentContext ? JSON.stringify(shipmentContext) : "No specific shipment selected"}

Guidelines:
1. Provide concise, professional, operationally precise advice.
2. If drafting an email or shipping instruction, include clear subject line, recipient placeholders, container/BL references, and professional closing.
3. If explaining demurrage/detention, clearly distinguish container detention (outside port terminal) from demurrage (inside port terminal).
4. Strictly comply with safety rule: Never claim that AI can autonomously sign, approve, or file customs declarations or bills of lading without authorized human sign-off.
5. Format with markdown bullet points and bold highlights for legibility.`;

        const response = await ai.models.generateContent({
          model: "gemini-3.8-flash",
          contents: message,
          config: {
            systemInstruction,
          },
        });

        if (response.text) {
          return NextResponse.json({
            success: true,
            isAiPowered: true,
            text: response.text,
          });
        }
      } catch (geminiError: any) {
        console.warn(
          "Gemini API returned error for assistant (falling back to copilot engine):",
          geminiError?.message || geminiError
        );
      }
    }

    // Intelligent logistics rule engine fallback
    const q = String(message).toLowerCase();
    let reply = "";

    if (q.includes("arrival notice") || q.includes("email") || q.includes("draft")) {
      const ref = shipmentContext?.shipmentNumber || "FF360-2026-000842";
      const vessel = shipmentContext?.vesselName || "MSC PALOMA V.MP2641W";
      const consignee = shipmentContext?.consigneeName || "EuroTech Precision Importers GmbH";
      reply = `**Subject:** Pre-Arrival Notice & Delivery Order Guidance — ${ref} / ${vessel}

**Dear Import Logistics Desk (${consignee}),**

Please be advised that your consignment is currently in maritime transit and approaching the Port of Discharge as detailed below:

* **Shipment Reference:** ${ref}
* **Master B/L No:** ${shipmentContext?.blNumber || "MEDU9812491"}
* **Vessel / Voyage:** ${vessel}
* **Port of Loading:** ${shipmentContext?.portOfLoading || "Nhava Sheva (INNSA)"}
* **Port of Discharge:** ${shipmentContext?.portOfDischarge || "Rotterdam (NLRTM)"}
* **Expected Time of Arrival (ETA):** Nov 08, 2026 @ 06:00 CET
* **Containers:** 2 x 40' HC (MSKU9482014, MSKU8194025)
* **Terminal Free Days:** 5 Days | **Carrier Free Time:** 14 Days

**Action Required for Delivery Order (D/O) Issuance:**
1. Please provide endorsed original Bill of Lading (or electronic telex release confirmation).
2. Settle destination local port handling charges and agent documentation disbursements.
3. Ensure custom T1 transit document / import declaration is filed with ECT Delta terminal.

For inquiries or container delivery coordination, contact the Rotterdam operations desk at ops@orientpacific.nl.

*Generated by FREIGHTFLOW 360 Copilot*`;
    } else if (q.includes("demurrage") || q.includes("detention") || q.includes("free time")) {
      reply = `### Key Differences: Demurrage vs. Detention (Maritime Logistics)

* **Terminal Demurrage:**
  * **Location:** Incurred inside the container terminal or container freight station (CFS).
  * **Trigger:** When loaded containers remain on the terminal wharf beyond the agreed **Terminal Free Time** (typically 3–5 working days).
  * **Payable To:** Terminal operator / Port authority or carrier holding terminal contract.

* **Carrier Detention (Per Diem):**
  * **Location:** Incurred outside the terminal gate.
  * **Trigger:** When an empty container is not returned to the shipping line's designated empty container depot within the **Carrier Free Days** (typically 10–14 days).
  * **Payable To:** Ocean carrier (e.g., MSC, Maersk, CMA CGM).

* **Operational Recommendation:**
  For container **MRKU7102948** with 2 free days left, fast-track customs Out of Charge (OOC) and prioritize NorthStar intermodal haulage dispatch to return empty shells before per-diem accrues ($125/day).`;
    } else if (q.includes("customs") || q.includes("icegate") || q.includes("leo") || q.includes("document")) {
      reply = `### Statutory Customs Documentation Checklist (CBIC & Global Standards)

For smooth clearance and issuance of the **Let Export Order (LEO)** or **Out of Charge (OOC)**:

1. **Commercial Invoice (Signed):** Must detail buyer/seller GSTIN, IEC, Incoterms, and invoice value breakdown.
2. **Detailed Packing List:** Net and gross weights per carton, pallet marks, and container seal numbers.
3. **Bill of Lading (or Draft BL):** Shipper, consignee, notify party matching invoice exactly.
4. **VGM (Verified Gross Mass) Slip:** Solas Convention weighbridge certificate.
5. **Certificate of Origin (CoO):** Issued by authorized Chamber of Commerce.
6. **E-Way Bill (Part A & B):** Mandatory for intermodal road haulage to port gate.

*Note:* Document cross-check revealed a 500 kg gross weight discrepancy in shipment FF360-2026-000842. Reconcile this before customs filing.`;
    } else {
      reply = `**Logistics Analysis for ${shipmentContext?.shipmentNumber || "FF360-2026-000842"}:**

* **Status:** In Transit across the Mediterranean Sea corridor.
* **Commodity:** ${shipmentContext?.commodity || "100% Combed Organic Cotton Yarns"}.
* **Gross Margin:** +17.5% ($1,300 net profit on $7,440 invoiced revenue).
* **Next Milestone:** Arrival at Rotterdam ECT Delta Terminal on Nov 08, 2026.
* **Compliance Note:** Ensure amended Packing List gross weight is synchronized with the weighbridge slip prior to discharge.

How else can I assist with this consignment?`;
    }

    return NextResponse.json({
      success: true,
      isAiPowered: false,
      text: reply,
    });
  } catch (error: any) {
    console.error("Assistant Service Error:", error);
    return NextResponse.json(
      {
        success: false,
        error: error.message || "Failed to generate AI response",
      },
      { status: 500 }
    );
  }
}
